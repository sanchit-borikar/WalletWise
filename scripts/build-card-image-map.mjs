/**
 * Writes src/components/cardImagesGenerated.ts so the app can load every approved
 * card image. Metro needs a literal require() per file, hence this generated map.
 *
 * Input:  assets/card-images/manifest.json (written by fetch-card-images.mjs)
 *         assets/card-images/approved.json (card ids whose picture was checked by eye)
 * Run:    npm run build:images
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'card-images');
const manifest = JSON.parse(readFileSync(join(dir, 'manifest.json'), 'utf8'));
const approvedPath = join(dir, 'approved.json');
const approved = existsSync(approvedPath) ? new Set(JSON.parse(readFileSync(approvedPath, 'utf8'))) : new Set();

const lines = [];
for (const [id, m] of Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b))) {
  if (m.status !== 'downloaded' || !approved.has(id)) continue;
  if (!existsSync(join(dir, m.file))) continue;
  lines.push(`  '${id}': require('../../assets/card-images/${m.file}'),`);
}

writeFileSync(
  join(root, 'src', 'components', 'cardImagesGenerated.ts'),
  `// Generated by scripts/build-card-image-map.mjs. Do not edit.
// Card artwork belongs to the issuing banks; sources are listed in assets/card-images/manifest.json.
export const DOWNLOADED_CARD_IMAGES: Record<string, number> = {
${lines.join('\n')}
};
`,
);
console.log(`Mapped ${lines.length} card images.`);
